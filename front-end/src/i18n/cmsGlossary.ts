// Look up a CMS value in the glossary (case-insensitive). Returns the translation
// for `lang`, or null if the value / language isn't covered.
export const glossaryLookup = (value: string, lang: Lang): string | null => {
  const trimmed = value.trim();
  if (!trimmed) return null;
  const entry =
    CMS_GLOSSARY[trimmed] ??
    CMS_GLOSSARY[Object.keys(CMS_GLOSSARY).find((k) => k.toLowerCase() === trimmed.toLowerCase()) ?? ''];
  return entry?.[lang] ?? null;
};
